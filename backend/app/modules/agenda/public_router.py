logger = logging.getLogger(__name__)

public_router = APIRouter()

# Booking-slot granularity. Configurable per clinic via
# ``clinic.settings.booking.slot_minutes``; defaults to 30.
_DEFAULT_SLOT_MINUTES = 30
_MAX_SLOT_RANGE_DAYS = 60  # never look further ahead than 60 days
_BOOKING_WINDOW_DAYS = 120  # patients may book up to this many days out


# ---------------------------------------------------------------------------
# Clinic resolution through the opaque booking token
# ---------------------------------------------------------------------------


def _booking_settings(clinic: Any) -> dict:
    """Pull ``clinic.settings.booking`` (never raises on a missing/malformed blob)."""
    s = clinic.settings
    if not isinstance(s, dict):
        return {}
    b = s.get("booking")
    return b if isinstance(b, dict) else {}


async def _clinic_by_booking_token(db: AsyncSession, token: str) -> Any:
    """Resolve a clinic by its opaque ``booking.public_token``.

    Uses raw SQL on ``clinics.settings`` (JSONB @>) so we never load the
    full ORM graph and never leak timing between "unknown token" — the
    JSONB containment scan is index-backed in PG and returns the same
    cost-class regardless of whether the token is absent or belongs to a
    different tenant.
    """
    row = (
        await db.execute(
            text(
                """
                SELECT id, name, timezone, currency, phone, email, address, settings
                FROM clinics
                WHERE (settings->'booking') ? 'public_token'
                  AND settings->'booking'->>'public_token' = :token
                """
            ),
            {"token": token},
        )
    ).first()
    return row


def _reject_token() -> HTTPException:
    # Constant 404, fresh per call — no oracle (the token is the access factor).
    return HTTPException(status_code=404, detail="Schedule link not found")


