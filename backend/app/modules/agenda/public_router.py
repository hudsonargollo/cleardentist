@public_router.get(
    "/public/schedule/{token}/meta",
    response_model=ApiResponse[PublicScheduleMeta],
)
@limiter.limit("60/minute")
async def get_schedule_meta(
    request: Request,
    token: str,
    db: AsyncSession = Depends(get_db),
) -> ApiResponse[PublicScheduleMeta]:
    clinic = await _clinic_by_booking_token(db, token)
    if clinic is None:
        raise _reject_token()
    b = _booking_settings(clinic)
    tz = safe_zone(clinic.timezone)
    # Default working window 09:00-18:00 clinic-local; overridable per clinic.
    day_start = b.get("day_start", "09:00")
    day_end = b.get("day_end", "18:00")
    slot_minutes = int(b.get("slot_minutes", _DEFAULT_SLOT_MINUTES))
    professionals = await _bookable_professionals(db, clinic.id, tz)
    return ApiResponse(
        data=PublicScheduleMeta(
            clinic_name=clinic.name,
            clinic_phone=clinic.phone,
            clinic_email=clinic.email,
            clinic_address_line=_address_line(clinic.address),
            clinic_language=str((clinic.settings or {}).get("communication_language") or "es"),
            clinic_currency=clinic.currency,
            timezone=str(tz),
            slot_minutes=slot_minutes,
            day_start=day_start,
            day_end=day_end,
            professionals=professionals,
        )
    )


def _address_line(address: dict | None) -> str | None:
    if not address:
        return None
    parts = [address.get("street"), address.get("city"), address.get("postal_code")]
    return ", ".join(str(p) for p in parts) or None


async def _bookable_professionals(db: AsyncSession, clinic_id: UUID, tz: Any) -> list[dict[str, Any]]:
    """Dentists + hygienists in the clinic that the patient may book.

    Reads ``clinic_memberships`` (is_professional) joined to ``users``.
    """
    rows = (
        await db.execute(
            text(
                """
                SELECT u.id, u.first_name, u.last_name
                FROM clinic_memberships m
                  JOIN users u ON u.id = m.user_id
                WHERE m.clinic_id = :cid
                  AND m.is_professional = TRUE
                  AND u.is_active = TRUE
                ORDER BY u.first_name, u.last_name
                """
            ),
            {"cid": str(clinic_id)},
        )
    ).fetchall()
    return [
        {"id": r.id, "name": f"{r.first_name} {r.last_name}".strip()} for r in rows
    ]


# ---------------------------------------------------------------------------
# /availability — free slots for one day
# ---------------------------------------------------------------------------


@public_router.get(
    "/public/schedule/{token}/availability",
    response_model=ApiResponse[list[str]],
)
@limiter.limit("120/minute")
async def get_availability(
    request: Request,
    token: str,
    start: date_type = Query(..., description="Day to query, YYYY-MM-DD (clinic-local)"),
    professional_id: UUID | None = None,
    db: AsyncSession = Depends(get_db),
) -> ApiResponse[list[str]]:
    clinic = await _clinic_by_booking_token(db, token)
    if clinic is None:
        raise _reject_token()
    b = _booking_settings(clinic)
    tz = safe_zone(clinic.timezone)
    slot_minutes = int(b.get("slot_minutes", _DEFAULT_SLOT_MINUTES))
    day_start = _parse_clock(b.get("day_start", "09:00"), tz, start)
    day_end = _parse_clock(b.get("day_end", "18:00"), tz, start)

    # Clamp the requested day into the booking-ahead window so the public
    # endpoint can't be used to mine availability far in the future.
    today_local = datetime.now(tz).date()
    if start < today_local or start > today_local + timedelta(days=_BOOKING_WINDOW_DAYS):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"start must be between {today_local} and "
            f"{today_local + timedelta(days=_BOOKING_WINDOW_DAYS)}",
        )

    day_start_utc = day_start.astimezone(UTC_ZONE)
    day_end_utc = day_end.astimezone(UTC_ZONE)

    # Booked (non-cancelled) appointments overlapping this day.
    booked_rows = (
        await db.execute(
            text(
                """
                SELECT start_time, end_time
                FROM appointments
                WHERE clinic_id = :cid
                  AND status <> 'cancelled'
                  AND start_time < :day_end
                  AND end_time > :day_start
                """
                + (
                    " AND professional_id = :pid" if professional_id else ""
                )
            ),
            {
                "cid": str(clinic.id),
                "day_start": day_start_utc,
                "day_end": day_end_utc,
                **({"pid": str(professional_id)} if professional_id else {}),
            },
        )
    ).fetchall()
    booked = [(r.start_time, r.end_time) for r in booked_rows]

    slots: list[str] = []
    cursor = day_start_utc
    end_cursor = day_end_utc - timedelta(minutes=slot_minutes)
    while cursor <= end_cursor:
        candidate_end = cursor + timedelta(minutes=slot_minutes)
        # Collision test against booked ranges.
        if not any(cursor < b_end and candidate_end > b_start for b_start, b_end in booked):
            slots.append(cursor.astimezone(tz).isoformat())
        cursor = candidate_end
    return ApiResponse(data=slots)


def _parse_clock(value: str, tz: Any, day: date_type) -> datetime:
    """Parse a ``HH:MM`` wall-clock into a clinic-local datetime on ``day``."""
    hh, mm = value.split(":")
    return datetime.combine(day, time(int(hh), int(mm)), tzinfo=tz)


UTC_ZONE = __import__("datetime").timezone.utc


# ---------------------------------------------------------------------------
# /book — patient self-books a slot
# ---------------------------------------------------------------------------


@public_router.post(
    "/public/schedule/{token}/book",
    response_model=ApiResponse[BookAppointmentOut],
)
@limiter.limit("10/minute")
async def public_book_appointment(
    request: Request,
    token: str,
    body: BookAppointmentIn,
    db: AsyncSession = Depends(get_db),
) -> ApiResponse[BookAppointmentOut]:
    clinic_row = await _clinic_by_booking_token(db, token)
    if clinic_row is None:
        raise _reject_token()

    clinic_id = clinic_row.id
    tz = safe_zone(clinic_row.timezone)

    # Normalize the requested start/end to UTC instants (patient sends
    # aware ISO datetimes, usually in the clinic tz).
    start_utc = body.start_time.astimezone(UTC_ZONE)
    end_utc = body.end_time.astimezone(UTC_ZONE)
    if start_utc >= end_utc:
        raise HTTPException(400, detail="start_time must precede end_time")

    # Re-validate the slot isn't double-booked (the unique index would
    # catch it, but a clean 409 message is friendlier).
    clash = (
        await db.execute(
            select(Appointment.id).where(
                Appointment.clinic_id == clinic_id,
                Appointment.status != "cancelled",
                Appointment.professional_id == body.professional_id,
                Appointment.start_time < end_utc,
                Appointment.end_time > start_utc,
            )
        )
    ).scalar_one_or_none()
    if clash is not None:
        raise HTTPException(409, detail="Time slot is no longer available")

    # Resolve or create the patient (identity by email within the clinic).
    patient = await _resolve_or_create_patient(db, clinic_id, body.patient)

    # Create the appointment (scheduled) then immediately confirm it.
    appointment = await AppointmentService.create_appointment(
        db,
        clinic_id,
        {
            "patient_id": patient.id,
            "professional_id": body.professional_id,
            "start_time": start_utc,
            "end_time": end_utc,
            "treatment_type": body.treatment_type,
            "status": "scheduled",
        },
        created_by=None,
    )
    await AppointmentService.transition(
        db, appointment, "confirmed", changed_by=None, note="self-scheduled online"
    )
    await db.refresh(appointment)

    sent = await _send_booking_confirmation(
        db, clinic_row, appointment, patient, tz
    )
    await db.commit()

    return ApiResponse(data=BookAppointmentOut(
        appointment_id=appointment.id,
        status=appointment.status,
        patient_id=patient.id,
        start_time=appointment.start_time,
        end_time=appointment.end_time,
        confirmation_sent=sent,
    ))


async def _resolve_or_create_patient(
    db: AsyncSession, clinic_id: UUID, body: BookPatientIn
) -> Any:
    """Match an existing active patient by email within the clinic, else create."""
    from app.modules.patients.models import Patient

    existing = (
        await db.execute(
            select(Patient).where(
                Patient.clinic_id == clinic_id,
                func.lower(Patient.email) == func.lower(body.email),
                Patient.status == "active",
            )
        )
    ).scalar_one_or_none()
    if existing is not None:
        return existing

    patient = Patient(
        clinic_id=clinic_id,
        first_name=body.first_name,
        last_name=body.last_name,
        email=body.email,
        phone=body.phone,
    )
    db.add(patient)
    await db.flush()
    await event_bus.publish(
        EventType.PATIENT_CREATED,
        {"patient_id": str(patient.id), "clinic_id": str(clinic_id)},
        db=db,
    )
    return patient


async def _send_booking_confirmation(
    db: AsyncSession, clinic: Any, appointment: Appointment, patient: Any, tz: Any
) -> bool:
    """Send the Resend confirmation email with the .ics attachment."""
    from app.core.email import email_service
    from app.core.email.providers.base import EmailMessage

    if not settings.EMAIL_ENABLED:
        return False
    if not patient.email:
        return False

    local_start = appointment.start_time.astimezone(tz)
    summary = appointment.treatment_type or "Dental consultation"
    subject = f"Confirmación de cita — {clinic.name or 'ClearDentist'}"

    body_html = (
        f"<p>Hola {patient.first_name} {patient.last_name},</p>"
        f"<p>Confirmada tu cita el <strong>{local_start.strftime('%A %d/%m/%Y %H:%M')}</strong>"
        f" con {appointment.professional.full_name if appointment.professional else ''}.\n</p>"
        f"<p>Tratamiento: {summary}</p>"
        f"<p>Teléfono de la clínica: {clinic.phone or '—'}</p>"
        f"<p>Puedes añadir esta cita a tu calendario adjuntando el archivo .ics.</p>"
        f"<p>— ClearDentist</p>"
    )

    try:
        ics = build_appointment_ics(appointment, clinic)  # clinic is a SQLAlchemy row proxy
    except Exception as exc:  # ics only needs a few clinic attrs
        logger.warning("ics export failed for %s: %s", appointment.id, exc)
        ics = None

    attachments = [
        {
            "filename": f"cita-{appointment.id}.ics",
            "content": ics,
            "mime_type": "text/calendar",
        }
    ] if ics else []

    message = EmailMessage(
        to_email=patient.email,
        to_name=f"{patient.first_name} {patient.last_name}".strip(),
        subject=subject,
        body_html=body_html,
        attachments=attachments,
    )
    result = await email_service.send(message, db=db, clinic_id=clinic.id)
    return result.status == "success"


