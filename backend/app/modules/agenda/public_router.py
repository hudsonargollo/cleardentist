class PublicScheduleMeta(BaseModel):
    clinic_name: str | None = None
    clinic_phone: str | None = None
    clinic_email: str | None = None
    clinic_address_line: str | None = None
    clinic_language: str
    clinic_currency: str
    timezone: str
    slot_minutes: int
    day_start: str
    day_end: str
    professionals: list[dict[str, Any]]


class BookPatientIn(BaseModel):
    first_name: str = Field(..., min_length=1, max_length=100)
    last_name: str = Field(..., min_length=1, max_length=100)
    email: EmailStr
    phone: str | None = Field(default=None, max_length=20)


class BookAppointmentIn(BaseModel):
    patient: BookPatientIn
    professional_id: UUID
    start_time: datetime
    end_time: datetime
    treatment_type: str | None = Field(default=None, max_length=100)

    @field_validator("start_time", "end_time")
    @classmethod
    def _require_aware(cls, v: datetime) -> datetime:
        if v.tzinfo is None:
            raise ValueError("must be an aware datetime")
        return v


class BookAppointmentOut(BaseModel):
    appointment_id: UUID
    status: str
    patient_id: UUID
    start_time: datetime
    end_time: datetime
    confirmation_sent: bool


