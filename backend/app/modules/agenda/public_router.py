"""Patient-facing public booking endpoints (no staff auth).

The booking token lives in ``clinic.settings.booking.public_token`` — an
opaque, unguessable string (secrets.token_urlsafe(32)) generated by a
clinic staff member under ``agenda.bookings.manage``. The token is the
*only* access factor (same posture as the budget public link — ADR 0006):
no clinic_id is exposed to the caller, so knowing/guessing another
clinic's token is the only way in.

Three endpoints:
  GET  /api/v1/agenda/public/schedule/{token}/meta
  GET  /api/v1/agenda/public/schedule/{token}/availability?start=YYYY-MM-DD[&professional_id=...]
  POST /api/v1/agenda/public/schedule/{token}/book

Rate-limited via slowapi (shared ``limiter`` from core/auth/router.py):
meta 60/min, availability 120/min (read-only), book 10/min (writes).
"""

